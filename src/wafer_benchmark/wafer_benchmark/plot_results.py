#!/usr/bin/env python3
"""
plot_results.py
===============
Reads the latest CSV generated by metrics_logger and generates the two key Pareto plots:
1. Placement Error vs. Cycle Time
2. Peak Jerk vs. Cycle Time
"""
import os
import glob
import pandas as pd
import matplotlib.pyplot as plt

def main():
    pkg_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    res_dir = os.path.join(pkg_dir, 'results')
    
    # Find latest csv
    latest_csv = os.path.join(res_dir, 'sweep_20260917_225703.csv')
    print(f"Reading {latest_csv}")
    
    df = pd.read_csv(latest_csv)
    # Filter only successful for error plotting
    df_success = df[df['success'] == True]
    
    if df_success.empty:
        print("No successful cycles found in data.")
        return

    # Group by target cycle time
    grouped = df_success.groupby('target_cycle_time')
    
    means = grouped.mean(numeric_only=True)
    stds = grouped.std(numeric_only=True)
    
    # Plot 1: Error vs Cycle Time
    plt.figure(figsize=(10, 5))
    
    plt.subplot(1, 2, 1)
    plt.errorbar(means.index, means['pos_error_mm'], yerr=stds['pos_error_mm'], fmt='o-', capsize=5, label='Position Error')
    plt.xlabel('Target Cycle Time (s)')
    plt.ylabel('Error (mm)')
    plt.title('Placement Error vs. Cycle Time')
    plt.grid(True)
    plt.legend()
    
    # Plot 2: Jerk vs Cycle Time
    plt.subplot(1, 2, 2)
    plt.plot(means.index, means['peak_jerk'], 's-', color='red')
    plt.xlabel('Target Cycle Time (s)')
    plt.ylabel('Peak Jerk (rad/s³)')
    plt.title('Peak Jerk vs. Cycle Time\n(Particle Risk Proxy)')
    plt.grid(True)
    
    plt.tight_layout()
    out_png = latest_csv.replace('.csv', '.png')
    plt.savefig(out_png)
    print(f"Plot saved to {out_png}")
    # plt.show()

if __name__ == '__main__':
    main()
